        p = papers[peer["title"]]
        peer.update(entity=f"paper:{p['arxiv']}", url=f"https://arxiv.org/abs/{p['arxiv']}", date=p["date"][:7],
                    authors=", ".join(p["authors"][:3]), venue=p["venue"], source="tracker")
