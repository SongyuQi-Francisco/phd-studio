def touch(out: Path) -> None:
    """Mark the demo's network caches fresh again (scholar metrics 1 day, follow feeds 6 h, ACL volumes 14 days),
    so the app keeps showing the invented data instead of asking OpenAlex / arXiv."""
    data, now = out / "data", time.time()
    for f in [*(data / "follow_feed").glob("*.json"), *(data / "scholars").glob("*.json")]:
        os.utime(f, (now, now))
    for f in (data / "sources" / "acl").glob("*.json"):
        d = json.loads(f.read_text(encoding="utf-8"))
        d["t"] = now
        f.write_text(json.dumps(d), encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help=f"output folder (default: {DEFAULT_OUT})")
    ap.add_argument("--fresh", action="store_true", help="delete the previous demo first (downloaded PDFs are kept)")
    ap.add_argument("--secrets", type=Path, help="folder with claude.env / deepseek.env to use (not copied)")
    ap.add_argument("--venues-from", type=Path, help="copy the venue catalog from this folder instead of downloading it")
    ap.add_argument("--no-pdfs", action="store_true", help="don't download arXiv PDFs")
    ap.add_argument("--touch", action="store_true", help="only mark the demo's caches fresh (run before screenshots)")
    a = ap.parse_args()
    out = a.out.expanduser().resolve()
    if a.touch:
        touch(out)
        print(f"caches in {out / 'data'} marked fresh")
        return
    if out == PROJECT or PROJECT.is_relative_to(out):
        sys.exit("--out must be a separate folder")
    if a.fresh and out.exists():
        for child in out.iterdir():
            if child.name != "downloads":
                shutil.rmtree(child) if child.is_dir() else child.unlink()
    elif out.exists() and (out / "DemoVault").exists():
        sys.exit(f"{out} already has a demo; use --fresh to rebuild it")
    secrets = (a.secrets.expanduser().resolve() if a.secrets else out / "secrets")
    cfg = build(out, secrets, a.venues_from.expanduser().resolve() if a.venues_from else None, not a.no_pdfs)
    print(f"\nDemo ready. Start it with:\n  STUDIO_CONFIG='{cfg}' STUDIO_DEVICE=demo uv run uvicorn app.main:app --port 8790")


if __name__ == "__main__":
    main()
